// Контур рамки сообщения, снятый со скриншота X-COM: Enemy Within.
//
// Путь рисуется прямо в разметке, поэтому его приходится держать здесь, а не в
// стилях: координаты нужны скрипту, а sass про них не знает.
//
// Пропорции взяты с картинки и приведены к системе координат 1000 × 395: точка
// отсчёта — левый край панели и верхняя кромка левого участка. В игре панель
// шириной около 1280 и высотой 385 слева, так что масштаб вышел один и тот же по
// обеим осям — диагонали остаются диагоналями.
//
// Что здесь необычного и всё это снято со скриншота:
//   - ступенька-выступ на верхней кромке, примерно на трети ширины;
//   - правый верхний угол скошен;
//   - правый нижний угол образует выступ, опущенный ниже остального низа;
//   - левый нижний угол скошен;
//   - толщина кромки разная: слева толще и светлее.

const VIEW = '0 0 1000 395';

// Весь контур целиком.
const OUTLINE = [
    'M 8 0',
    'L 324 16', // верхняя кромка идёт вниз
    'L 360 62', // выступ: резкий сход вниз
    'L 965 82',
    'L 1000 94', // скошенный правый верхний угол
    'L 1000 383',
    'L 782 394', // нижняя кромка идёт вниз к выступу справа
    'L 765 367', // выступ снизу: ступенька вверх
    'L 51 332',
    'L 0 301', // скошенный левый нижний угол
    'L 0 0',
    'Z',
].join(' ');

// Левая часть отдельно: в игре она толще и светится сильнее остальных.
const EDGE = ['M 8 0', 'L 324 16', 'M 0 0', 'L 0 301'].join(' ');

// Яркие короткие отрезки у двух углов. В игре кромка не равномерная: она
// разгорается под три места — у левого края, перед правым верхним углом и у
// левого нижнего. Равномерная линия выглядит как рамка из фотошопа, а не как
// приборная панель.
const ACCENTS = [
    'M 900 82 L 963 82', // перед правым верхним углом
    'M 52 332 L 140 339', // у левого нижнего угла
    'M 0 262 L 0 301', // низ левого края, до самого угла
].join(' ');

// Тонкая линия внутри, параллельная верхней кромке на левом участке.
const WHISPER = 'M 16 26 L 318 42';

// buildFrame returns the frame of one message.
//
// Разметка своя и постоянная, из данных чата в неё ничего не попадает, но и
// innerHTML тут не нужен: пути строятся узлами, и ни одна строка не приходит из
//вне.
export function buildFrame() {
    const NS = 'http://www.w3.org/2000/svg';

    const svg = document.createElementNS(NS, 'svg');
    svg.setAttribute('class', 'msg__frame');
    svg.setAttribute('viewBox', VIEW);
    // none: панель тянется под любую ширину и высоту реплики, сохраняя форму.
    // Толщину при этом держит non-scaling-stroke в стилях.
    svg.setAttribute('preserveAspectRatio', 'none');
    svg.setAttribute('aria-hidden', 'true');
    svg.setAttribute('focusable', 'false');

    for (const [className, d] of [
        ['msg__frame-body', OUTLINE],
        ['msg__frame-glow', OUTLINE],
        ['msg__frame-line', OUTLINE],
        ['msg__frame-edge', EDGE],
        ['msg__frame-edge', ACCENTS],
        ['msg__frame-whisper', WHISPER],
    ]) {
        const path = document.createElementNS(NS, 'path');
        path.setAttribute('class', className);
        path.setAttribute('d', d);
        svg.append(path);
    }

    return svg;
}